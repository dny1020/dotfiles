-- Bootstrap de lazy.nvim (se auto-instala la primera vez; versiones fijadas en lazy-lock.json)
local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
if not (vim.uv or vim.loop).fs_stat(lazypath) then
  local repo = "https://github.com/folke/lazy.nvim.git"
  local out = vim.fn.system({ "git", "clone", "--filter=blob:none", "--branch=stable", repo, lazypath })
  if vim.v.shell_error ~= 0 then
    vim.api.nvim_echo({
      { "Error al clonar lazy.nvim:\n", "ErrorMsg" },
      { out, "WarningMsg" },
    }, true, {})
    vim.fn.getchar()
    os.exit(1)
  end
end
vim.opt.rtp:prepend(lazypath)

require("lazy").setup({
  spec = { { import = "plugins" } }, -- carga todo lua/plugins/*.lua
  install = { colorscheme = { "gruvbox" } },
  checker = { enabled = false }, -- sin chequeo automático de updates (reproducible vía lockfile)
  change_detection = { notify = false },
})
